# ========================================================================================
# DEBANK BALANCE CHECKER — Конфигурация
# ========================================================================================
# Основные параметры (потоки, ретраи, задержки) — в general_config.py
# Здесь только то, что влияет на отбор токенов и вид Excel-отчёта

# Не учитывать токены, помеченные DeBank как скам или подозрительные.
# Такие токены выбрасываются полностью и в отчёт не попадают.
SKIP_SCAM_TOKENS = True

# ── Что считать мусором ──────────────────────────────────────────────────
# Фарм-кошелькам массово прилетают аирдропы мусорных токенов: у них есть
# «биржевая» цена, но нет ликвидности. DeBank их скамом не метит и в свою
# оценку кошелька включает — у vitalik.eth DeBank показывает $1.16M, из
# которых настоящих активов около $78k. Флаги DeBank (is_core, is_verified)
# тут не помогают: у спама они такие же, как у ETH.
#
# Мусор в баланс не идёт, но из отчёта не пропадает: у него свой лист
# «Мусор» с причиной, а в сводке — отдельная колонка. Нативные монеты
# сетей (ETH, BNB, POL…) мусором не считаются никогда.

# Порог «рейтинга» токена (credit_score от DeBank). Ниже — позиция мусорная.
# Ориентиры по шкале: ETH ≈ 44 000 000, ENS ≈ 430 000, USDT в сети Core ≈ 13 000,
# свежий мем-токен — 0.
TRUSTED_CREDIT_SCORE = 10_000

# Доля всей эмиссии токена на одном кошельке, начиная с которой позиция —
# аирдроп-мусор. Настоящие активы на кошельке — это сотые доли процента
# эмиссии, а спамеры рассылают по 5–90% выпуска, чтобы сумма выглядела
# внушительно. 0.01 = 1%.
MAX_SUPPLY_SHARE = 0.01

# ── Excel-отчёт ──────────────────────────────────────────────────────────

# Минимальная стоимость позиции (USD) для попадания на лист «Токены».
# 0 — выгружать всё, включая пыль.
MIN_VALUE_USD = 0.0

# Минимальная сумма (USD) для начала цветного градиента ячеек.
# Ячейки дешевле останутся без заливки.
GRADIENT_MIN_USD = 0.20

# Сумма (USD), при которой градиент достигает максимальной насыщенности.
GRADIENT_MAX_USD = 1000.0
