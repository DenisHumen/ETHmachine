# Основные параметры (потоки, ретраи, задержки) — в general_config.py
# Здесь только то, что влияет на отбор токенов и вид Excel-отчёта

# Не учитывать токены, помеченные DeBank как скам или подозрительные.
# Такие токены выбрасываются полностью и в отчёт не попадают.
SKIP_SCAM_TOKENS = True

# Порог «рейтинга» токена (credit_score от DeBank), начиная с которого позиция
# считается надёжной.
#
# Зачем это нужно: фарм-кошелькам массово прилетают аирдропы мусорных токенов,
# у которых есть биржевая цена, но нет ликвидности. DeBank их скамом не метит
# и в свою оценку кошелька включает — отсюда и берутся «неправдоподобные»
# суммы вроде $300 000 на кошельке, где реально лежит доллар.
#
# Мы ничего не прячем: колонка «Всего, $» остаётся такой же, как на сайте
# DeBank, а рядом появляется «Надёжные, $» — сумма без мусора. Расхождение
# между ними сразу показывает, что сумма дутая.
#
# Ориентиры по шкале: ETH ≈ 38 000 000, ENS ≈ 400 000, свежий мем-токен — 0.
TRUSTED_CREDIT_SCORE = 10_000

# Минимальная стоимость позиции (USD) для попадания на лист «Токены».
# 0 — выгружать всё, включая пыль.
MIN_VALUE_USD = 0.0

# Минимальная сумма (USD) для начала цветного градиента ячеек.
# Ячейки дешевле останутся без заливки.
GRADIENT_MIN_USD = 0.20

# Сумма (USD), при которой градиент достигает максимальной насыщенности.
GRADIENT_MAX_USD = 1000.0
